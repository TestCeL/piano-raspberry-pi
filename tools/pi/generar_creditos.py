def en(texto):
    """Traducción al inglés de un texto del catálogo. ValueError si parece español y no está en TRADUCCION."""
    if texto in TRADUCCION:
        return TRADUCCION[texto]
    minus = f" {texto.lower()} "
    if LETRAS_ESPANOL & set(texto) or any(p in minus for p in PALABRAS_ESPANOL):
        raise ValueError(f"falta la traducción al inglés de «{texto}» (TRADUCCION en generar_creditos.py)")
    return texto


def celda(texto):
    return texto.replace("|", "\\|")


def tabla_sonidos(instrumentos, ingles):
    if ingles:
        filas = ["| Sound | Category | Author | License | Use | Source |", "|---|---|---|---|---|---|"]
    else:
        filas = ["| Sonido | Categoría | Autor | Licencia | Uso | Fuente |", "|---|---|---|---|---|---|"]
    for i in instrumentos:
        t = en if ingles else (lambda x: x)
        uso = t(i.uso)
        if i.restringido:
            uso = f"**{uso}**"
        categoria = CATEGORIA_EN[i.tipo] if ingles else cat.NOMBRE_CATEGORIA[i.tipo]
        filas.append(f"| {celda(t(i.nombre))} | {categoria} | {celda(t(i.autor))} | {celda(t(i.licencia))} | "
                     f"{celda(uso)} | <{i.fuente}> |")
    return "\n".join(filas)


