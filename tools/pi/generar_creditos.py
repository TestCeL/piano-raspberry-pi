def main(argv=None):
    ap = argparse.ArgumentParser(description="Genera CREDITOS.md y CREDITS.md desde el catálogo de instrumentos.")
    ap.add_argument("--catalogo", default=cat.RUTA_CATALOGO)
    ap.add_argument("--raiz", default=RAIZ)
    ap.add_argument("--comprobar", action="store_true", help="código 1 si los archivos no están al día")
    args = ap.parse_args(argv)
    try:
        archivos = generar(cat.cargar(args.catalogo, "/"))
    except (OSError, ValueError) as e:
        print(f"ERROR: {e}", file=sys.stderr)
        return 2
    desactualizados = []
    for nombre, contenido in archivos.items():
        ruta = os.path.join(args.raiz, nombre)
        if args.comprobar:
            try:
                with open(ruta, encoding="utf-8") as f:
                    actual = f.read()
            except OSError:
                actual = None
            if actual != contenido:
                desactualizados.append(nombre)
        else:
            with open(ruta, "w", encoding="utf-8", newline="\n") as f:
                f.write(contenido)
            print(f"escrito {ruta}")
    if desactualizados:
        print(f"desactualizados: {', '.join(desactualizados)} (ejecutar generar_creditos.py)", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
